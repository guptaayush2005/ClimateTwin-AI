def generate_districts_dataset():
    records = []
    
    total_districts = sum(len(dists) for dists in DISTRICTS_DATA.values())
    print(f"Compiling {len(DISTRICTS_DATA)} States/UTs with {total_districts} Districts...")

    for state, dist_list in DISTRICTS_DATA.items():
        defaults = STATE_CLIMATE_DEFAULTS.get(state, {"temp": 26.0, "rain": 3.0, "humidity": 65.0, "aqi": 90, "risk": "Medium"})
        
        for idx, d in enumerate(dist_list):
            dist_name = d["district"]
            lat = round(d["lat"], 4)
            lon = round(d["lon"], 4)
            
            # Subtle variation based on latitude/longitude
            lat_factor = (lat - 20.0) * 0.15
            lon_factor = (lon - 80.0) * 0.1
            
            temp = round(defaults["temp"] - lat_factor * 0.5 + (idx % 5 - 2) * 0.4, 2)
            rain = max(0.0, round(defaults["rain"] + (idx % 7 - 3) * 0.35, 2))
            humidity = min(98.0, max(25.0, round(defaults["humidity"] + (idx % 6 - 2.5) * 1.2, 1)))
            aqi = max(15, int(defaults["aqi"] + (idx % 9 - 4) * 4))
            
            # Determine Risk
            if aqi >= 150 or temp >= 35.0 or rain >= 35.0:
                risk = "High"
            elif aqi >= 100 or temp >= 31.0 or rain >= 15.0:
                risk = "Medium"
            else:
                risk = "Low"
                
            records.append({
                "State": state,
                "District": dist_name,
                "Latitude": lat,
                "Longitude": lon,
                "Temperature": temp,
                "Rainfall": rain,
                "Humidity": humidity,
                "AQI": aqi,
                "Risk": risk
            })

    # Save to JSON
    json_path = DATA_DIR / "india_districts.json"
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(records, f, indent=2, ensure_ascii=False)
    print(f"✅ Generated JSON: {json_path} ({len(records)} records)")

    # Save to CSV
    csv_path = DATA_DIR / "districts_climate_data.csv"
    df = pd.DataFrame(records)
    df.to_csv(csv_path, index=False, encoding="utf-8")
    print(f"✅ Generated CSV: {csv_path} ({len(df)} rows)")

    # Create State -> Districts map for ultra-fast front-end lookup
    state_district_map = {}
    for state, dist_list in DISTRICTS_DATA.items():
        state_district_map[state] = [d["district"] for d in dist_list]
    
    map_path = DATA_DIR / "state_districts_map.json"
    with open(map_path, "w", encoding="utf-8") as f:
        json.dump(state_district_map, f, indent=2, ensure_ascii=False)
    print(f"✅ Generated State-District Hierarchy: {map_path}")

    return records

if __name__ == "__main__":
    generate_districts_dataset()
