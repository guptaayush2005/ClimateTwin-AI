let currentLanguage = localStorage.getItem("climatetwin_lang") || "en";

function t(key, lang = currentLanguage) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS["en"];
  return dict[key] || TRANSLATIONS["en"][key] || key;
}

function updatePageTranslations(lang) {
  currentLanguage = lang;
  localStorage.setItem("climatetwin_lang", lang);

  // Update all elements with data-i18n
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    el.textContent = t(key, lang);
  });

  // Update all placeholders with data-i18n-placeholder
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    el.placeholder = t(key, lang);
  });

  // Update language select dropdown value if present
  const langSelect = document.getElementById("languageSelect");
  if (langSelect && langSelect.value !== lang) {
    langSelect.value = lang;
  }

  // Trigger chart/view re-render if function exists
  if (typeof window.onLanguageChanged === "function") {
    window.onLanguageChanged(lang);
  }
}
